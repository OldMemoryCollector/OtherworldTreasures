    private static string _lastExample="";
    private static string RandomDrinkExample()
    {
        string text="";
        for(int attempt=0;attempt<8;attempt++)
        {
            bool catalog=System.Random.Shared.Next(4)==0;var names=catalog?SCP294Potion.CatalogDrinkNames().ToArray():Array.Empty<string>();
            var drink=DrinkExamples[System.Random.Shared.Next(DrinkExamples.Length)];string name=names.Length>0?names[System.Random.Shared.Next(names.Length)]:Scp294InputText.Text(drink.Zh,drink.En,drink.En);
            int style=System.Random.Shared.Next(3);
            text=style switch
            {
                0=>Scp294InputText.Text($"来一杯{name}吗？",$"How about {name}?",$"{name}はいかが？"),
                1=>Scp294InputText.Text($"试试{name}吧。",$"Try {name}.",$"{name}を試してみる？"),
                _=>Scp294InputText.Text($"今天想喝{name}吗？",$"Would you like {name}?",$"今日は{name}にする？")
            };
            if(text!=_lastExample)break;
        }
        _lastExample=text;return text;
    }
